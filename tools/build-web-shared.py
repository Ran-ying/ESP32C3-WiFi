#!/usr/bin/env python3
"""Bundle the shared local parallel engine/PCAP parser for ESP-IDF embedding."""
from pathlib import Path
import sys
root=Path(__file__).resolve().parents[1]
bundles={
 'web/parallel-worker.js':['web/crypto.js','standalone/src/pcap.js','standalone/src/engine.js','standalone/src/worker.js'],
 'web/parallel.js':['standalone/src/source.js','standalone/src/pool.js'],
}
for target,paths in bundles.items():
    text='// Generated by tools/build-web-shared.py; edit shared source files.\n'+'\n;\n'.join((root/p).read_text() for p in paths)
    out=root/target
    if '--check' in sys.argv:
        if not out.exists() or out.read_text()!=text:raise SystemExit(f'{target} is stale')
    else:out.write_text(text)
print('PASS web shared bundles match sources' if '--check' in sys.argv else 'Built shared web bundles')
